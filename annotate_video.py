def detect_scenes(video_path):
    """ 
    Takes a path to a video file, returns a scene list. Scenes are detected using PySceneDetect.
    """
    print(f"starting scene detection for {video_path}")
    scene_list = detect(video_path, AdaptiveDetector())
    print(f"detected {len(scene_list)} scenes in {video_path} ")
    return scene_list

def get_frames(video_path, scene_list):
    """
    Takes a videopath and the scenelist and splits outputs frames (images) per scene based on the timesamps in the scene list.
    """
    frames = save_images(
                    scene_list,
                    open_video(video_path), #takes video_path and turns it into a VideoStream object
                    interval=1.0,     # 1 frame is saved per  seconds of video (ints are frames, floats are seconds!)
                    min_images=1, # if the scene is shorter than 15 seconds
                    frame_margin= 0.1, # waits 0.5 seconds for the first frame
                    output_dir=f"frames/{video_path.removeprefix("data/")}",
                    image_extension="jpg",
                    show_progress=True 
                    ) 
    
    return frames

def transcribe_audio(video_path):
    """
    Transcribes the speech in a video's audio using Whisper.
    Returns:
        segments: list of faster_whisper Segment objects (with word timestamps)
        full_transcription: the complete text as one string
    """
    print("starting transcription of audio")

    model = WhisperModel("large-v3-turbo", device="cpu", compute_type="int8", cpu_threads=8)
    segments, info = model.transcribe(
        video_path,
        language="nl",
        vad_filter=True,
        word_timestamps=True,
        beam_size=1,
    )

    segments = list(segments)

    full_transcription = "\n".join(s.text.strip() for s in segments)

    print("transcription completed")
    return segments, full_transcription

