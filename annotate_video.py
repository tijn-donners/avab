def map_transcription_to_scene(scene_list, segments, scene_number):
    """
    Map the words with timestamps from segments to the scenes in the scenelist
    """
    scene_start = scene_list[scene_number - 1][0].seconds
    scene_end = scene_list[scene_number - 1][1].seconds
    
    
    scene_transcription = []
    for segment in segments:
        for word in segment.words:
            if word.start >= scene_start and word.end < scene_end:
                scene_transcription.append(word.word)

    print("".join(scene_transcription).strip())
    return "".join(scene_transcription).strip()

def extract_toegang_inventarisnummer(bestandnaam):
    """
    Takes bestandnaam (filename) and returns corresponding toegang and inventarisnummer
    """
    # retrieve toegansnummer and inventarisnummer from filename
    _, toegang, inventaris = Path(bestandnaam).stem.split('_')
    inventarisnummer = inventaris.lstrip('0')
    return toegang, inventarisnummer 

def retrieve_original_description(bestandnaam):
    """
    This function retrieves metadata from MAIS Exports based on filename (toegang and inventarisnummer)
    """

    toegang, inventarisnummer = extract_toegang_inventarisnummer(bestandnaam)

    # retrieves contents of <AHD> tag based on nested <NUMMER> tag
    for _, element in ET.iterparse(f"mais_metadata/{toegang}_1_386_flexis.xml", events=("end",)):
        if element.tag == "AHD":
            value = element.findtext(".//NUMMER")
            if value is not None and value.strip() == str(inventarisnummer).strip():
                metadata = ET.tostring(element, encoding="unicode")
            element.clear()


    toegang_titel = None
    # retreive the name of the top-level archieftoegang from ther mais xml export
    for _, elem in ET.iterparse(f"mais_metadata/{toegang}_1_386_flexis.xml", events=("end",)):
        if elem.tag == "AHD":                          # eerste complete AHD-blok
            value = elem.find("AWE[NAAM='TITEL']/WAARDE")
            if value is not None:
                toegang_titel = value.text
            break              

    return metadata, toegang_titel

